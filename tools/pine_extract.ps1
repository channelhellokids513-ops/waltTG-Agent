param([string]$Src = $(throw "required: -Src <path to Market Gravity .pine>"),
      [string]$Out = "MG_SOURCE_EXCERPTS.md")
$l = Get-Content $Src -Encoding UTF8

# (label, start, end) -- start/end are 1-based inclusive; start=0 means "locate by regex"
$fixed = @(
    @('state-declarations-upper', 558, 600),
    @('removePoolAtIndex',         780, 830),
    @('addPoolMember',             830, 1010),
    @('strength-averaging',       1010, 1130),
    @('getBaseFreshnessHalfLife', 1331, 1357),
    @('detect-upper-liquidity',   2744, 2934),
    @('previous-completed-day',   3124, 3308),
    @('lifecycle-persistent',     3308, 3516),
    @('find-strongest-downside',  3516, 3580),
    @('rank-weighted-pull',       3752, 3840)
)

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# Market Gravity — verbatim Pine source excerpts (Fase 0 transcription aid)')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('Generated by tools/pine_extract.ps1 from MG.txt. Do not hand-edit; regenerate instead.')
[void]$sb.AppendLine('Line numbers are 1-based in MG.txt (4630 lines).')
[void]$sb.AppendLine('')

foreach ($r in $fixed) {
    $name = $r[0]; $s = [int]$r[1]; $e = [int]$r[2]
    [void]$sb.AppendLine("## $name  (L$s-L$e)")
    [void]$sb.AppendLine('```pinescript')
    for ($i = $s; $i -le [Math]::Min($e, $l.Count); $i++) {
        $t = $l[$i - 1]
        if ($t.Trim() -eq '') { continue }
        if ($t.TrimStart().StartsWith('//') -and $t.Trim().Length -lt 4) { continue }
        [void]$sb.AppendLine(('{0}| {1}' -f $i, $t.TrimEnd()))
    }
    [void]$sb.AppendLine('```')
    [void]$sb.AppendLine('')
}

# locate-by-name helper for small functions referenced but not yet placed
$wanted = @('getDistanceToZoneATR', 'getPivotProminence', 'containsSource', 'pruneOldestPool', 'touchCount')
foreach ($w in $wanted) {
    $found = $null
    for ($i = 0; $i -lt $l.Count; $i++) {
        if ($l[$i] -match ('^{0}\(' -f [regex]::Escape($w))) { $found = $i + 1; break }
    }
    if ($null -eq $found) {
        [void]$sb.AppendLine("## $w  -- NOT FOUND as a top-level function definition")
        [void]$sb.AppendLine('')
        continue
    }
    $e = [Math]::Min($l.Count, $found + 34)
    [void]$sb.AppendLine("## $w  (located L$found, showing $found-L$e)")
    [void]$sb.AppendLine('```pinescript')
    for ($i = $found; $i -le $e; $i++) {
        $t = $l[$i - 1]
        if ($t.Trim() -eq '') { continue }
        [void]$sb.AppendLine(('{0}| {1}' -f $i, $t.TrimEnd()))
        if ($i -gt $found -and $t -match '^\S' -and $t -notmatch ('^{0}\(' -f [regex]::Escape($w))) { break }
    }
    [void]$sb.AppendLine('```')
    [void]$sb.AppendLine('')
}

Set-Content -Path $Out -Value $sb.ToString() -Encoding UTF8
Write-Output "wrote $Out"
Write-Output ("bytes={0} lines={1}" -f (Get-Item $Out).Length, (Get-Content $Out).Count)
